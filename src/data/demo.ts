function assignment(
  exhibitorId: string,
  category: ServiceAssignment['category'],
  providerId: string,
  phases: ServiceAssignment['phases'],
  contractStatus: ServiceAssignment['contractStatus'] = 'included',
  producerId = 'carlos-mendes',
  serviceId = 'bianca-souza',
): ServiceAssignment {
  return {
    id: `${exhibitorId}-${category}-${phases.join('-')}`,
    eventId: demoEvent.id,
    exhibitorId,
    category,
    phases,
    providerId,
    contractStatus,
    primaryProducerId: producerId,
    secondaryProducerId: producerId === 'carlos-mendes' ? 'marcos-lima' : undefined,
    providerServiceId: serviceId,
  };
}

